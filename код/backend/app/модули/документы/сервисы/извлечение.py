# ── Основная функция ──────────────────────────────────────────────────────────

def _очистить_json(текст: str) -> str:
    """Убирает markdown-блоки если LLM всё же завернул в ```json ... ```."""
    текст = текст.strip()
    # Убрать ```json ... ``` или ``` ... ```
    match = re.search(r"```(?:json)?\s*([\s\S]+?)\s*```", текст)
    if match:
        return match.group(1)
    return текст


async def извлечь_поля(
    документ: Документ,
    сессия: AsyncSession,
) -> ExtractedFields:
    """
    Вызывает LLM, извлекает поля из текста документа, сохраняет в ExtractedFields.
    Если запись уже существует — обновляет.
    """
    from sqlalchemy import select
    логгер.info("извлечение_полей", документ_id=str(документ.id), тип=документ.тип)

    промпт = ПРОМПТЫ_ПО_ТИПУ.get(документ.тип, ПРОМПТ_УНИВЕРСАЛЬНЫЙ)
    сообщения = [
        {"role": "system", "content": СИСТЕМНЫЙ_ПРОМПТ},
        {"role": "user", "content": f"{промпт}\n\n{документ.текст}"},
    ]

    сырой_ответ = await вызвать_llm(сообщения, модель=настройки.llm_модель_извлечения)

    # Парсим JSON
    try:
        поля = json.loads(_очистить_json(сырой_ответ))
    except json.JSONDecodeError:
        логгер.warning("json_парсинг_неудача", ответ=сырой_ответ[:200])
        поля = {"сырой_ответ": сырой_ответ, "ошибка": "не удалось распарсить JSON"}

    # Upsert ExtractedFields
    существующий = (await сессия.execute(
        select(ExtractedFields).where(ExtractedFields.документ_id == документ.id)
    )).scalars().first()

    if существующий:
        существующий.поля = поля
        существующий.модель_использована = настройки.llm_модель_извлечения
        существующий.схема_версия = "v1"
        существующий.извлечено_когда = datetime.now(timezone.utc)
        сессия.add(существующий)
        результат = существующий
    else:
        результат = ExtractedFields(
            документ_id=документ.id,
            поля=поля,
            модель_использована=настройки.llm_модель_извлечения,
            схема_версия="v1",
        )
        сессия.add(результат)

    await сессия.commit()
    логгер.info("извлечение_завершено", полей=len(поля))
    return результат
