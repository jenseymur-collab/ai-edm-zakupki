"""
AI-сервис: сравнение двух версий документа.

LLM выявляет изменения между версиями, классифицирует их
по значимости и оценивает юридические/коммерческие риски.
"""

import structlog
from sqlalchemy.ext.asyncio import AsyncSession

from app.общее.llm_client import вызвать_llm
from app.общее.конфиг import настройки
from app.модули.документы.модели import Документ

логгер = structlog.get_logger()

# ── Промпт ─────────────────────────────────────────────────────────────────────

СИСТЕМНЫЙ = """Ты — юридический AI-ассистент системы документооборота закупок.
Сравнивай версии договоров и документов: чётко описывай изменения, оценивай риски."""

ПРОМПТ_СРАВНЕНИЕ = """Сравни две версии документа и выяви все изменения.

Тип документа: {тип}
Номер: {номер}

=== ВЕРСИЯ {версия_1} (ИСХОДНАЯ) ===
{текст_1}

=== ВЕРСИЯ {версия_2} (НОВАЯ) ===
{текст_2}

Задача:
1. Выяви ВСЕ изменения (даже незначительные)
2. Для каждого изменения укажи: что было → что стало
3. Оцени значимость каждого изменения: КРИТИЧНО / ВАЖНО / НЕЗНАЧИТЕЛЬНО
4. Дай итоговую оценку риска: ВЫСОКИЙ / СРЕДНИЙ / НИЗКИЙ

Структура ответа:
📝 ИЗМЕНЕНИЯ:
[нумерованный список с оценкой каждого]

⚖️ ОЦЕНКА РИСКОВ:
[разбор потенциальных рисков]

🎯 ИТОГ:
[общий вывод: что изменилось принципиально, рекомендация — принять/отклонить/обсудить]"""


# ── Основная функция ──────────────────────────────────────────────────────────

async def сравнить_версии(
    документ_1: Документ,
    документ_2: Документ,
    сессия: AsyncSession,
) -> dict:
    """
    Сравнивает два документа через LLM.

    документ_1 — исходная (старшая) версия
    документ_2 — новая версия

    Возвращает:
    {
        документ_1_id, документ_2_id,
        тип, номер,
        анализ: str (текст от LLM),
        версия_1, версия_2
    }
    """
    логгер.info(
        "сравнение_документов",
        v1=str(документ_1.id),
        v2=str(документ_2.id),
    )

    промпт = ПРОМПТ_СРАВНЕНИЕ.format(
        тип=документ_1.тип,
        номер=документ_1.номер or "не указан",
        версия_1=документ_1.версия,
        текст_1=документ_1.текст[:6000],   # обрезаем для контекста
        версия_2=документ_2.версия,
        текст_2=документ_2.текст[:6000],
    )

    сообщения = [
        {"role": "system", "content": СИСТЕМНЫЙ},
        {"role": "user", "content": промпт},
    ]

    анализ = await вызвать_llm(сообщения, модель=настройки.llm_модель_сравнения)

    логгер.info("сравнение_завершено", символов=len(анализ))
    return {
        "документ_1_id": str(документ_1.id),
        "документ_2_id": str(документ_2.id),
        "тип": документ_1.тип,
        "номер": документ_1.номер,
        "версия_1": документ_1.версия,
        "версия_2": документ_2.версия,
        "анализ": анализ,
    }
