"""
AI-сервис: семантический поиск по документам через pgvector (cosine similarity).

Алгоритм:
1. Получить эмбеддинг запроса через OpenRouter
2. Найти top-5 ближайших векторов в таблице эмбеддингов (cosine distance)
3. Вернуть документы с score и фрагментом текста
"""

import structlog
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from app.общее.llm_client import получить_эмбеддинг

логгер = structlog.get_logger()

# Количество результатов по умолчанию
TOP_N = 5


async def семантический_поиск(
    запрос: str,
    сессия: AsyncSession,
    топ: int = TOP_N,
) -> list[dict]:
    """
    Выполняет семантический поиск по базе эмбеддингов.

    Возвращает список словарей:
    {
        документ_id, сделка_id, тип, номер, статус,
        score (0..1, чем выше — тем ближе),
        фрагмент (первые 300 символов текста)
    }
    """
    логгер.info("семантический_поиск", запрос=запрос[:80])

    # 1. Эмбеддинг запроса
    вектор_запроса = await получить_эмбеддинг(запрос)
    вектор_строка = "[" + ",".join(str(x) for x in вектор_запроса) + "]"

    # 2. Cosine similarity через pgvector: 1 - cosine_distance
    # <=> — оператор cosine distance в pgvector (0 = идентично, 2 = противоположно)
    sql = text("""
        SELECT
            э.документ_id,
            д.сделка_id,
            д.тип,
            д.номер,
            д.статус,
            д.текст,
            1 - (э.вектор <=> CAST(:вектор AS vector)) AS score
        FROM "документы"."эмбеддинги" э
        JOIN "документы"."документы" д ON д.id = э.документ_id
        WHERE д.активная = TRUE
        ORDER BY э.вектор <=> CAST(:вектор AS vector)
        LIMIT :топ
    """)

    строки = (await сессия.execute(
        sql,
        {"вектор": вектор_строка, "топ": топ},
    )).mappings().all()

    результаты = []
    for строка in строки:
        текст_полный = строка["текст"] or ""
        результаты.append({
            "документ_id": str(строка["документ_id"]),
            "сделка_id": str(строка["сделка_id"]),
            "тип": строка["тип"],
            "номер": строка["номер"],
            "статус": строка["статус"],
            "score": round(float(строка["score"]), 4),
            "фрагмент": текст_полный[:300].strip(),
        })

    логгер.info("поиск_завершён", найдено=len(результаты))
    return результаты
