"""
AI-сервис: создание и массовое обновление эмбеддингов документов.

Используется:
- при загрузке нового документа (фоновая задача из роутера)
- через POST /ai/embeddings/backfill (для seed-данных и ручного перезапуска)
"""

import structlog
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.общее.llm_client import получить_эмбеддинг
from app.модули.документы.модели import Документ, Эмбеддинг

логгер = structlog.get_logger()

МОДЕЛЬ_ЭМБЕДДИНГОВ = "openai/text-embedding-3-small"


async def создать_или_обновить_эмбеддинг(
    документ_id,
    сессия: AsyncSession,
) -> bool:
    """
    Создаёт или обновляет эмбеддинг для документа.

    Returns:
        True — успешно, False — ошибка (нет текста или сбой LLM)
    """
    документ = await сессия.get(Документ, документ_id)
    if not документ or not (документ.текст or "").strip():
        логгер.warning(
            "эмбеддинг_пропущен",
            документ_id=str(документ_id),
            причина="нет текста или документ не найден",
        )
        return False

    try:
        вектор = await получить_эмбеддинг(документ.текст)
    except Exception as е:
        логгер.error("эмбеддинг_ошибка_llm", документ_id=str(документ_id), ошибка=str(е))
        return False

    # Upsert: если уже есть — обновить вектор, иначе создать
    существующий = (await сессия.execute(
        select(Эмбеддинг).where(Эмбеддинг.документ_id == документ_id)
    )).scalars().first()

    if существующий:
        существующий.вектор = вектор
        существующий.модель_использована = МОДЕЛЬ_ЭМБЕДДИНГОВ
        сессия.add(существующий)
    else:
        сессия.add(Эмбеддинг(
            документ_id=документ_id,
            вектор=вектор,
            модель_использована=МОДЕЛЬ_ЭМБЕДДИНГОВ,
        ))

    await сессия.commit()
    логгер.info("эмбеддинг_сохранён", документ_id=str(документ_id))
    return True


async def backfill_эмбеддингов(сессия: AsyncSession) -> dict:
    """
    Создаёт эмбеддинги для всех активных документов, у которых ещё нет вектора.

    Порядок: по дате загрузки (новые первыми).
    Время работы: ~2-3 сек на документ (вызов OpenRouter).

    Returns:
        {"обработано": N, "успешно": M, "ошибки": K}
    """
    подзапрос_уже_есть = select(Эмбеддинг.документ_id)

    документы = (await сессия.execute(
        select(Документ).where(
            Документ.активная.is_(True),
            ~Документ.id.in_(подзапрос_уже_есть),
        ).order_by(Документ.загружен_когда.desc())
    )).scalars().all()

    обработано = len(документы)
    успешно = 0
    ошибки = 0

    логгер.info("backfill_начат", документов=обработано)

    for документ in документы:
        ok = await создать_или_обновить_эмбеддинг(документ.id, сессия)
        if ok:
            успешно += 1
        else:
            ошибки += 1

    логгер.info(
        "backfill_завершён",
        обработано=обработано,
        успешно=успешно,
        ошибки=ошибки,
    )
    return {"обработано": обработано, "успешно": успешно, "ошибки": ошибки}
