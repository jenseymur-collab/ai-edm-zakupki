"""
AI-сервис: анализ задержек и рисков согласования по сделке.

LLM анализирует все визы сделки, выявляет просрочки,
оценивает риски и рекомендует действия.
"""

from datetime import datetime, timezone

import structlog
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.общее.llm_client import вызвать_llm
from app.общее.конфиг import настройки
from app.модули.документы.модели import Документ
from app.модули.согласование.модели import Виза, МаршрутСогласования, ШагМаршрута
from app.модули.сделки.модели import Сделка

логгер = structlog.get_logger()

# ── Промпт ─────────────────────────────────────────────────────────────────────

СИСТЕМНЫЙ = """Ты — AI-ассистент системы управления закупками фармацевтической компании.
Анализируй риски задержек в согласовании документов. Будь конкретным, указывай даты и сроки."""

ПРОМПТ_ЗАДЕРЖКИ = """Проанализируй статус согласования документов по сделке закупки.

Сделка: {номер} — {название}
Сумма: {сумма} {валюта}
Текущая дата: {сегодня}

Визы согласования:
{визы}

Задача:
1. Выяви все просроченные визы (дедлайн прошёл, решение не поставлено)
2. Оцени риски: какие визы могут просрочиться в ближайшие 3 дня
3. Укажи, сколько дней уже просрочено для каждого случая
4. Дай рекомендации: кому нужно срочно эскалировать

Структура ответа:
🔴 ПРОСРОЧЕНО: [список с деталями]
🟡 ПОД УГРОЗОЙ: [список виз с дедлайном в ближайшие 3 дня]
📋 РЕКОМЕНДАЦИИ: [конкретные действия]
📊 ИТОГ: [общая оценка ситуации 1-2 предложения]"""


# ── Основная функция ──────────────────────────────────────────────────────────

async def проанализировать_задержки(
    сделка: Сделка,
    сессия: AsyncSession,
) -> dict:
    """
    Анализирует задержки в согласовании по сделке через LLM.

    Возвращает:
    {
        просрочено: int,
        под_угрозой: int,
        анализ: str (текст от LLM),
        визы_детали: [список виз с метаданными]
    }
    """
    логгер.info("анализ_задержек", сделка_id=str(сделка.id))
    сейчас = datetime.now(timezone.utc)

    # Получаем все документы сделки
    документы = (await сессия.execute(
        select(Документ).where(Документ.сделка_id == сделка.id)
    )).scalars().all()
    uid_документов = [д.id for д in документы]
    словарь_документов = {д.id: д for д in документы}

    if not uid_документов:
        return {
            "просрочено": 0,
            "под_угрозой": 0,
            "анализ": "Документов по сделке нет.",
            "визы_детали": [],
        }

    # Все визы по документам сделки
    визы = (await сессия.execute(
        select(Виза).where(Виза.документ_id.in_(uid_документов))
        .order_by(Виза.дедлайн)
    )).scalars().all()

    if not визы:
        return {
            "просрочено": 0,
            "под_угрозой": 0,
            "анализ": "Визы согласования по сделке не найдены.",
            "визы_детали": [],
        }

    # Собираем шаги для отображения ролей
    шаг_ids = list({в.шаг_маршрута_id for в in визы})
    шаги_строки = (await сессия.execute(
        select(ШагМаршрута).where(ШагМаршрута.id.in_(шаг_ids))
    )).scalars().all()
    шаги = {ш.id: ш for ш in шаги_строки}

    маршрут_ids = list({в.маршрут_id for в in визы})
    маршруты_строки = (await сессия.execute(
        select(МаршрутСогласования).where(МаршрутСогласования.id.in_(маршрут_ids))
    )).scalars().all()
    маршруты = {м.id: м for м in маршруты_строки}

    # Формируем строки виз для промпта
    строки_виз = []
    просрочено = 0
    под_угрозой = 0
    визы_детали = []

    from datetime import timedelta
    за_3_дня = сейчас + timedelta(days=3)

    for виза in визы:
        шаг = шаги.get(виза.шаг_маршрута_id)
        маршрут = маршруты.get(виза.маршрут_id)
        документ = словарь_документов.get(виза.документ_id)

        роль = шаг.роль if шаг else "неизвестно"
        порядок = шаг.порядок if шаг else "?"
        тип_дока = документ.тип if документ else "?"
        номер_дока = документ.номер if документ else "?"
        дедлайн_str = виза.дедлайн.strftime("%d.%m.%Y") if виза.дедлайн else "нет"

        # Вычисляем просрочку
        просрочено_дней = None
        if виза.решение is None and виза.дедлайн:
            дельта = сейчас - виза.дедлайн
            если_просрочено = дельта.total_seconds() > 0
            просрочено_дней = int(дельта.days) if если_просрочено else None
            if если_просрочено:
                просрочено += 1
            elif виза.дедлайн <= за_3_дня:
                под_угрозой += 1

        статус_визы = (
            f"✅ СОГЛАСОВАНО ({виза.решено_когда.strftime('%d.%m.%Y') if виза.решено_когда else ''})"
            if виза.решение == "согласовано"
            else f"❌ ОТКЛОНЕНО" if виза.решение == "отклонено"
            else f"🔴 ПРОСРОЧЕНО на {просрочено_дней} дн." if просрочено_дней
            else f"⏳ ОЖИДАЕТ (дедлайн {дедлайн_str})" if виза.шаг_статус == "активен"
            else f"🔜 В ОЧЕРЕДИ (дедлайн {дедлайн_str})"
        )

        строки_виз.append(
            f"Шаг {порядок} | Роль: {роль} | Документ: {тип_дока} №{номер_дока} | "
            f"Дедлайн: {дедлайн_str} | {статус_визы}"
        )

        визы_детали.append({
            "виза_id": str(виза.id),
            "документ_id": str(виза.документ_id),
            "тип_документа": тип_дока,
            "роль": роль,
            "порядок": порядок,
            "статус": виза.шаг_статус,
            "решение": виза.решение,
            "дедлайн": виза.дедлайн.isoformat() if виза.дедлайн else None,
            "просрочено_дней": просрочено_дней,
        })

    промпт = ПРОМПТ_ЗАДЕРЖКИ.format(
        номер=сделка.номер,
        название=сделка.название,
        сумма=str(сделка.сумма or "не указана"),
        валюта=сделка.валюта,
        сегодня=сейчас.strftime("%d.%m.%Y"),
        визы="\n".join(строки_виз),
    )

    сообщения = [
        {"role": "system", "content": СИСТЕМНЫЙ},
        {"role": "user", "content": промпт},
    ]

    анализ = await вызвать_llm(сообщения, модель=настройки.llm_модель_задержек)

    логгер.info("задержки_проанализированы", просрочено=просрочено, под_угрозой=под_угрозой)
    return {
        "просрочено": просрочено,
        "под_угрозой": под_угрозой,
        "анализ": анализ,
        "визы_детали": визы_детали,
    }
