"""
AI-сервис: проверка полноты пакета документов по сделке.

LLM сверяет имеющиеся документы с чеклистом для профиля сделки
и возвращает: что есть, чего не хватает, общий вердикт.
"""

import structlog
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.общее.llm_client import вызвать_llm
from app.общее.конфиг import настройки
from app.модули.документы.модели import Документ
from app.модули.сделки.модели import Сделка, ПРОФИЛЬ_СТАНДАРТ, ПРОФИЛЬ_МАЛАЯ

логгер = structlog.get_logger()

# ── Чеклисты по профилям ───────────────────────────────────────────────────────

ЧЕКЛИСТ_СТАНДАРТ = [
    "заявка_на_закупку",
    "коммерческое_предложение",
    "протокол_выбора",
    "договор",
    "спецификация",
    "акт",
    "счёт_фактура",
]

ЧЕКЛИСТ_МАЛАЯ = [
    "заявка_на_закупку",
    "коммерческое_предложение",
    "договор",
    "акт",
    "счёт_фактура",
]

ЧЕКЛИСТЫ = {
    ПРОФИЛЬ_СТАНДАРТ: ЧЕКЛИСТ_СТАНДАРТ,
    ПРОФИЛЬ_МАЛАЯ: ЧЕКЛИСТ_МАЛАЯ,
}

# ── Промпт ─────────────────────────────────────────────────────────────────────

СИСТЕМНЫЙ = """Ты — AI-ассистент системы закупок фармацевтической компании.
Анализируй полноту пакета документов по сделке. Будь чётким и конкретным."""

ПРОМПТ_ПОЛНОТА = """Проверь полноту пакета документов для сделки закупки.

Профиль сделки: {профиль}
Сумма: {сумма} {валюта}

Требуемые типы документов (чеклист):
{чеклист}

Загруженные документы (активные):
{документы}

Задача: проверь, все ли необходимые документы присутствуют.
Для каждого типа из чеклиста укажи: есть / отсутствует.
В конце — общий вердикт: пакет полный / неполный, и что нужно добавить.

Ответ структурируй:
1. Статус по каждому типу документа (✅ есть / ❌ отсутствует)
2. Итог: полный или неполный пакет
3. Что нужно загрузить (если неполный)
4. Дополнительные замечания (если есть)"""


# ── Основная функция ──────────────────────────────────────────────────────────

async def проверить_полноту(
    сделка: Сделка,
    сессия: AsyncSession,
) -> dict:
    """
    Проверяет полноту пакета документов через LLM.

    Возвращает:
    {
        полный: bool,
        анализ: str (текст от LLM),
        есть: [типы],
        отсутствуют: [типы],
        чеклист: [типы]
    }
    """
    логгер.info("проверка_полноты", сделка_id=str(сделка.id), профиль=сделка.профиль)

    # Получаем активные документы сделки
    документы = (await сессия.execute(
        select(Документ).where(
            Документ.сделка_id == сделка.id,
            Документ.активная.is_(True),
        )
    )).scalars().all()

    чеклист = ЧЕКЛИСТЫ.get(сделка.профиль, ЧЕКЛИСТ_СТАНДАРТ)

    # Строка со списком документов для промпта
    если_документы = [
        f"- {д.тип} (№{д.номер}, статус: {д.статус})"
        for д in документы
    ]
    строка_документов = "\n".join(если_документы) if если_документы else "Документов нет"

    строка_чеклист = "\n".join(f"- {т}" for т in чеклист)

    промпт = ПРОМПТ_ПОЛНОТА.format(
        профиль=сделка.профиль,
        сумма=str(сделка.сумма or "не указана"),
        валюта=сделка.валюта,
        чеклист=строка_чеклист,
        документы=строка_документов,
    )

    сообщения = [
        {"role": "system", "content": СИСТЕМНЫЙ},
        {"role": "user", "content": промпт},
    ]

    анализ = await вызвать_llm(сообщения, модель=настройки.llm_модель_извлечения)

    # Простая эвристика для флага полный/неполный (по наличию типов)
    имеющиеся_типы = {д.тип for д in документы}
    отсутствуют = [т for т in чеклист if т not in имеющиеся_типы]
    есть = [т for т in чеклист if т in имеющиеся_типы]
    полный = len(отсутствуют) == 0

    логгер.info("полнота_проверена", полный=полный, отсутствует=len(отсутствуют))
    return {
        "полный": полный,
        "анализ": анализ,
        "есть": есть,
        "отсутствуют": отсутствуют,
        "чеклист": чеклист,
    }
