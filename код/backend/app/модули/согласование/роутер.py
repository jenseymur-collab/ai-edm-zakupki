"""Роутер согласования: цепочка виз, визирование, просроченные."""

import uuid
from datetime import datetime, timedelta, timezone

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.общее.база_данных import получить_сессию
from app.модули.аудит.модели import Событие
from app.модули.документы.модели import Документ, СТАТУС_СОГЛАСОВАН, СТАТУС_ОТКЛОНЁН
from app.модули.согласование.модели import (
    МаршрутСогласования, ШагМаршрута, Виза,
    МАРШРУТ_ЗАВЕРШЁН,
    ШАГ_АКТИВЕН, ШАГ_ЗАКРЫТ, ШАГ_ОЖИДАЕТ,
    РЕШЕНИЕ_СОГЛАСОВАНО, РЕШЕНИЕ_ОТКЛОНЕНО,
)
from app.модули.согласование.схемы import (
    ЗапросВизы, ОтветВизирования, ВизаОтвет, ЦепочкаСогласования,
)

роутер = APIRouter()


@роутер.get("/documents/{doc_id}/approvals",
            response_model=ЦепочкаСогласования,
            summary="Цепочка согласования документа")
async def цепочка_согласования(
    doc_id: uuid.UUID,
    сессия: AsyncSession = Depends(получить_сессию),
):
    """Возвращает все визы документа с информацией о шагах маршрута."""
    документ = await сессия.get(Документ, doc_id)
    if not документ:
        raise HTTPException(status_code=404, detail="Документ не найден")

    визы = (await сессия.execute(
        select(Виза).where(Виза.документ_id == doc_id)
        .order_by(Виза.дедлайн)
    )).scalars().all()

    if not визы:
        return ЦепочкаСогласования(
            документ_id=doc_id,
            визы=[],
            завершено=True,
        )

    сейчас = datetime.now(timezone.utc)
    маршрут = await сессия.get(МаршрутСогласования, визы[0].маршрут_id)

    # Шаги маршрута для обогащения виз
    шаги = {
        ш.id: ш for ш in (await сессия.execute(
            select(ШагМаршрута).where(ШагМаршрута.маршрут_id == визы[0].маршрут_id)
        )).scalars().all()
    }

    текущий_шаг = None
    результат_виз = []
    for виза in визы:
        шаг = шаги.get(виза.шаг_маршрута_id)
        ов = ВизаОтвет.model_validate(виза)
        ов.просрочена = (
            виза.решение is None and виза.дедлайн < сейчас
        )
        if шаг:
            ов.роль_шага = шаг.роль
            ов.порядок_шага = шаг.порядок
        if виза.шаг_статус == ШАГ_АКТИВЕН:
            текущий_шаг = шаг.порядок if шаг else None
        результат_виз.append(ов)

    завершено = all(в.маршрут_статус == МАРШРУТ_ЗАВЕРШЁН for в in визы)

    return ЦепочкаСогласования(
        документ_id=doc_id,
        маршрут_название=маршрут.название if маршрут else None,
        визы=результат_виз,
        текущий_шаг=текущий_шаг,
        завершено=завершено,
    )


@роутер.post("/documents/{doc_id}/approve",
             response_model=ОтветВизирования,
             summary="Поставить визу (принять/отклонить)")
async def поставить_визу(
    doc_id: uuid.UUID,
    данные: ЗапросВизы,
    сессия: AsyncSession = Depends(получить_сессию),
):
    """
    Визирует текущий активный шаг документа.
    При согласовании активирует следующий шаг или закрывает маршрут.
    При отклонении — маршрут закрывается, документ получает статус «отклонён».
    """
    документ = await сессия.get(Документ, doc_id)
    if not документ:
        raise HTTPException(status_code=404, detail="Документ не найден")

    # Найти активную визу
    активная_виза = (await сессия.execute(
        select(Виза).where(
            Виза.документ_id == doc_id,
            Виза.шаг_статус == ШАГ_АКТИВЕН,
        )
    )).scalars().first()

    if not активная_виза:
        raise HTTPException(status_code=400, detail="Нет активного шага для визирования")

    # Проверка допустимости решения
    допустимые = {РЕШЕНИЕ_СОГЛАСОВАНО, РЕШЕНИЕ_ОТКЛОНЕНО, "на_доработку"}
    if данные.решение not in допустимые:
        raise HTTPException(
            status_code=422,
            detail=f"Недопустимое решение. Варианты: {допустимые}",
        )

    сейчас = datetime.now(timezone.utc)
    активная_виза.пользователь_id = данные.пользователь_id
    активная_виза.решение = данные.решение
    активная_виза.комментарий = данные.комментарий
    активная_виза.шаг_статус = ШАГ_ЗАКРЫТ
    активная_виза.решено_когда = сейчас
    сессия.add(активная_виза)

    следующий_порядок = None
    маршрут_завершён = False

    if данные.решение == РЕШЕНИЕ_СОГЛАСОВАНО:
        # Найти следующий шаг (ОЖИДАЕТ)
        следующая_виза = (await сессия.execute(
            select(Виза).where(
                Виза.документ_id == doc_id,
                Виза.маршрут_id == активная_виза.маршрут_id,
                Виза.шаг_статус == ШАГ_ОЖИДАЕТ,
            ).order_by(Виза.дедлайн)
        )).scalars().first()

        if следующая_виза:
            следующая_виза.шаг_статус = ШАГ_АКТИВЕН
            # Обновляем дедлайн от текущего момента
            шаг = await сессия.get(ШагМаршрута, следующая_виза.шаг_маршрута_id)
            if шаг:
                следующая_виза.дедлайн = сейчас + timedelta(days=шаг.срок_дни)
            сессия.add(следующая_виза)
            шаг_следующий = await сессия.get(ШагМаршрута, следующая_виза.шаг_маршрута_id)
            следующий_порядок = шаг_следующий.порядок if шаг_следующий else None
        else:
            # Все шаги закрыты — маршрут завершён
            маршрут_завершён = True
            все_визы = (await сессия.execute(
                select(Виза).where(
                    Виза.документ_id == doc_id,
                    Виза.маршрут_id == активная_виза.маршрут_id,
                )
            )).scalars().all()
            for в in все_визы:
                в.маршрут_статус = МАРШРУТ_ЗАВЕРШЁН
                сессия.add(в)
            документ.статус = СТАТУС_СОГЛАСОВАН
            сессия.add(документ)
    else:
        # Отклонено или на доработку — закрываем маршрут
        маршрут_завершён = True
        все_визы = (await сессия.execute(
            select(Виза).where(
                Виза.документ_id == doc_id,
                Виза.маршрут_id == активная_виза.маршрут_id,
            )
        )).scalars().all()
        for в in все_визы:
            в.маршрут_статус = МАРШРУТ_ЗАВЕРШЁН
            сессия.add(в)
        документ.статус = СТАТУС_ОТКЛОНЁН
        сессия.add(документ)

    # Журнал событий
    шаг_инфо = await сессия.get(ШагМаршрута, активная_виза.шаг_маршрута_id)
    сессия.add(Событие(
        тип="виза.поставлена",
        сущность_тип="виза",
        сущность_id=активная_виза.id,
        пользователь_id=данные.пользователь_id,
        данные={
            "решение": данные.решение,
            "роль": шаг_инфо.роль if шаг_инфо else None,
            "порядок": шаг_инфо.порядок if шаг_инфо else None,
            "комментарий": данные.комментарий,
        },
    ))
    if маршрут_завершён:
        сессия.add(Событие(
            тип="маршрут.завершён",
            сущность_тип="документ",
            сущность_id=документ_id,
            пользователь_id=данные.пользователь_id,
            данные={"итог": данные.решение},
        ))

    await сессия.commit()

    if маршрут_завершён:
        if данные.решение == РЕШЕНИЕ_СОГЛАСОВАНО:
            сообщение = "Маршрут завершён — документ согласован"
        else:
            сообщение = f"Маршрут завершён — документ {данные.решение}"
    else:
        сообщение = f"Виза поставлена, передано на шаг {следующий_порядок}"

    return ОтветВизирования(
        виза_id=активная_виза.id,
        решение=данные.решение,
        следующий_шаг=следующий_порядок,
        маршрут_завершён=маршрут_завершён,
        сообщение=сообщение,
    )
